CREATE TABLE IF NOT EXISTS mock_payos_state (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 order_id BIGINT NOT NULL UNIQUE,
 payment_attempt_id BIGINT NULL UNIQUE,
 order_code BIGINT NOT NULL UNIQUE,
 payment_link_id VARCHAR(255) NULL UNIQUE,
 amount DECIMAL(12,0) NOT NULL,
 currency VARCHAR(8) NOT NULL DEFAULT 'VND',
 expires_at DATETIME(6) NOT NULL,
 provider_status VARCHAR(32) NOT NULL DEFAULT 'NOT_CREATED',
 create_effect_status VARCHAR(32) NOT NULL DEFAULT 'NOT_REQUESTED',
 amount_paid DECIMAL(20,0) NOT NULL DEFAULT 0,
 amount_remaining DECIMAL(20,0) NOT NULL,
 transactions_json LONGTEXT NOT NULL,
 original_create_result LONGTEXT NULL,
 fault_state LONGTEXT NULL,
 cancel_requested BOOLEAN NOT NULL DEFAULT 0,
 version BIGINT NOT NULL DEFAULT 0,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 CONSTRAINT fk_mock_state_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 CONSTRAINT fk_mock_state_attempt FOREIGN KEY(payment_attempt_id) REFERENCES payment_attempts(id) ON DELETE RESTRICT,
 CONSTRAINT ck_mock_state_money CHECK(amount>0 AND amount_paid>=0 AND amount_remaining>=0),
 CONSTRAINT ck_mock_state_version CHECK(version>=0 AND version<=9007199254740991),
 CONSTRAINT ck_mock_state_currency CHECK(currency='VND'),
 CONSTRAINT ck_mock_state_status CHECK(provider_status IN ('NOT_CREATED','PENDING','PAID','FAILED','CANCELLED','EXPIRED','PROCESSING')),
 CONSTRAINT ck_mock_state_create CHECK(create_effect_status IN ('NOT_REQUESTED','IN_FLIGHT','CLOSED_WITHOUT_EFFECT','CREATED'))
);
CREATE TABLE IF NOT EXISTS mock_payos_actions (
 id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
 action_id CHAR(36) NOT NULL UNIQUE,
 order_id BIGINT NOT NULL,
 actor_id BIGINT NOT NULL,
 idempotency_key CHAR(36) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 scenario VARCHAR(64) NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'VERIFYING',
 reason VARCHAR(64) NULL,
 provider_state_id BIGINT NULL,
 lease_until DATETIME(6) NULL,
 runner_epoch BIGINT NOT NULL DEFAULT 0,
 effect_facts LONGTEXT NULL,
 result LONGTEXT NULL,
 audit_history LONGTEXT NOT NULL,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 completed_at DATETIME(6) NULL,
 CONSTRAINT uq_mock_action_intent UNIQUE(actor_id,order_id,idempotency_key),
 CONSTRAINT fk_mock_action_order FOREIGN KEY(order_id) REFERENCES orders(id) ON DELETE RESTRICT,
 CONSTRAINT fk_mock_action_actor FOREIGN KEY(actor_id) REFERENCES users(id) ON DELETE RESTRICT,
 CONSTRAINT fk_mock_action_state FOREIGN KEY(provider_state_id) REFERENCES mock_payos_state(id) ON DELETE RESTRICT,
 CONSTRAINT ck_mock_action_status CHECK(status IN ('VERIFYING','APPLIED','REJECTED')),
 CONSTRAINT ck_mock_action_epoch CHECK(runner_epoch>=0 AND runner_epoch<=9007199254740991),
 INDEX ix_mock_action_order_status(order_id,status,created_at),
 INDEX ix_mock_action_actor(actor_id,created_at)
);
